"""Compute the headline findings from the exported dashboard data and write docs/findings.md.

Every number quoted in the README comes from here, so the text cannot drift from the data:

    .venv/bin/python -m scripts.findings
"""

from __future__ import annotations

import json
import math
import statistics as st
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
DATA = ROOT / "dashboard" / "public" / "data"
SPECIALTY = ["E&S and specialty commercial", "Diversified specialty",
             "Bermuda and international specialty (re)insurance", "Niche specialty (workers' comp, medical liability)"]


def load(name: str):
    return json.loads((DATA / name).read_text())


def pct(v: float, d: int = 1) -> str:
    return f"{v * 100:.{d}f}%"


def pts(v: float, d: int = 1) -> str:
    return f"{'+' if v > 0 else '−' if v < 0 else ''}{abs(v) * 100:.{d}f} pts"


def quarter(iso: str) -> str:
    return f"Q{(int(iso[5:7]) + 2) // 3} {iso[:4]}"


def main() -> None:
    meta, comps, panel, macro, model, refs = (load(n) for n in ("meta.json", "companies.json", "panel.json", "macro.json",
                                                                 "model.json", "reference.json"))
    bt = load("backtest.json") if (DATA / "backtest.json").exists() else None
    by_cik = {c["cik"]: c for c in comps}
    q = panel["quarters"]
    ser = panel["series"]
    out: list[str] = ["# Findings", "", (f"Generated by `scripts/findings.py` from the data built {meta['built']} "
                      f"(financials through {quarter(meta['dataThrough'])})."), ""]

    spec = [c for c in comps if c["cohort"] == "specialty"]
    active = [c for c in spec if c["status"] == "active"]
    out += ["## Universe", "",
            (f"- {len(spec)} specialty carriers ({len(active)} active, {len(spec) - len(active)} acquired or exited), "
            f"{sum(c['cohort'] == 'benchmark' for c in comps)} standard-lines benchmark carriers "
            f"({sum(c['cohort'] == 'benchmark' and not c['comparable'] for c in comps)} flagged not comparable)."),
            (f"- {meta['xbrl']['facts']:,} XBRL facts ({meta['xbrl']['tags']:,} distinct tags), "
            f"{sum(c['filings'] for c in comps if c['cohort'] != 'ai_indicator'):,} filings in the insurers' EDGAR indexes."), ""]

    # industry shock: top quarters
    shock = macro["industryShock"]
    top = sorted(zip(shock["quarters"], shock["mean"], strict=True), key=lambda t: -(t[1] or -9))[:6]
    mq_index = {d: i for i, d in enumerate(macro["quarters"])}

    def corr_with(key: str, log: bool = True) -> tuple[float, int]:
        xs, ys = [], []
        for d, f in zip(shock["quarters"], shock["mean"], strict=True):
            i = mq_index.get(d)
            v = macro["values"].get(key, [None] * len(macro["quarters"]))[i] if i is not None else None
            if f is None or v is None:
                continue
            xs.append(f)
            ys.append(math.log1p(v) if log else v)
        return (st.correlation(xs, ys), len(xs)) if len(xs) > 3 else (float("nan"), len(xs))

    c_storm, n_storm = corr_with("storm_damage")
    c_bill, n_bill = corr_with("billion_cost")
    out += ["## The industry (catastrophe) shock", "",
            "Largest quarters of the latent shock the model infers from loss ratios alone: "
            + ", ".join(f"{quarter(d)} ({v:+.1f} sd)" for d, v in top) + ".",
            (f"No catastrophe data goes into the model, yet the shock correlates {c_storm:.2f} with log NOAA Storm Events "
            f"property damage ({n_storm} quarters) and {c_bill:.2f} with log NOAA billion-dollar disaster costs "
            f"({n_bill} quarters, through 2024)."), ""]

    # catastrophe sensitivity
    lam = [(c["ticker"], c["model"]["lam"][0]) for c in comps if c.get("model", {}).get("lam") and c["model"]["lam"][0] is not None]
    lam.sort(key=lambda t: -t[1])
    out += ["## Catastrophe sensitivity (loss-ratio points per 1 sd of the industry shock)", "",
            "- Highest: " + ", ".join(f"{t} {v * 100:.1f}" for t, v in lam[:5]),
            "- Lowest: " + ", ".join(f"{t} {v * 100:.1f}" for t, v in lam[-5:]), ""]

    # growth by segment (same-company, premium-weighted) at the last quarter
    def same_company_growth(ciks: list[int], i: int) -> float | None:
        now = before = 0.0
        n = 0
        for c in ciks:
            s = ser.get(str(c), {}).get("npe_ttm")
            if not s or i < 4:
                continue
            a, b = s[i], s[i - 4]
            if a and b and a > 0 and b > 0:
                now += a
                before += b
                n += 1
        return now / before - 1 if before > 0 and n >= 2 else None

    last = len(q) - 1
    segs = {seg: [c["cik"] for c in comps if c["comparable"] and c["segment"] == seg] for seg in SPECIALTY[:3]}
    segs["Standard-lines benchmark"] = [c["cik"] for c in comps if c["comparable"] and c["cohort"] == "benchmark"]
    out += ["## Premium growth, same company, trailing four quarters to " + quarter(q[last]), ""]
    out += [f"- {k}: {pct(g)}" for k, v in segs.items() if (g := same_company_growth(v, last)) is not None]
    growth = [ser[str(c['cik'])]['npe_growth_yoy'][last] for c in active if str(c['cik']) in ser]
    growth = [g for g in growth if g is not None]
    if growth:
        out.append(f"- Median active specialty carrier: {pct(st.median(growth))}")
    out.append("")

    # reserve development, premium-weighted specialty
    def weighted(metric: str, ciks: list[int], i: int) -> float | None:
        num = den = 0.0
        for c in ciks:
            s = ser.get(str(c), {})
            v, w = (s.get(metric) or [None] * len(q))[i], (s.get("npe_ttm") or [None] * len(q))[i]
            if v is not None and w:
                num += v * w
                den += w
        return num / den if den else None

    spec_ciks = [c["cik"] for c in spec if c["comparable"]]
    pyd = [(d, weighted("pyd_ratio_ttm", spec_ciks, i)) for i, d in enumerate(q) if d >= "2011-03-31"]
    fy = [v for d, v in pyd if d[5:7] == "12" and d >= "2011" and v is not None]
    recent = [v for d, v in pyd[-12:] if v is not None]
    out += ["## Reserve development (specialty, premium-weighted, TTM)", "",
            f"- Favorable in {sum(1 for _, v in pyd if v is not None and v < 0)} of {sum(1 for _, v in pyd if v is not None)} quarters.",
            f"- Fiscal-year average since 2011: {pts(st.mean(fy))}; average of the last 12 quarters: {pts(st.mean(recent))}.", ""]

    # benchmark composition (premium weights at the last quarter)
    bench = [c for c in comps if c["cohort"] == "benchmark" and c["comparable"]]
    w = {c["ticker"]: (ser.get(str(c["cik"]), {}).get("npe_ttm") or [None] * len(q))[last] or 0 for c in bench}
    tot = sum(w.values()) or 1
    out += ["## The standard-lines benchmark", "",
            "Premium weights at " + quarter(q[last]) + ": "
            + ", ".join(f"{t} {v / tot:.0%}" for t, v in sorted(w.items(), key=lambda kv: -kv[1])) + ".", ""]

    # AI capex
    mq = macro["quarters"]
    vals = macro["values"]
    k = max(i for i, v in enumerate(vals["ai_capex"]) if v is not None)
    out += ["## Hyperscaler capex (total capital expenditure of Microsoft, Alphabet, Amazon, Meta, from their filings)", "",
            (f"- {quarter(mq[k])}: ${vals['ai_capex'][k]:.0f}B in the quarter, {vals['ai_capex_yoy'][k]:+.0f}% year over year, "
            f"{vals['ai_capex_to_ocf'][k]:.0f}% of their operating cash flow (trailing four quarters)."), ""]

    # backtest
    if bt:
        y1, y2 = bt["annual"]["year1"], bt["annual"]["year2"]
        out += ["## Backtest (rolling origins " + f"{bt['origins'][0][:4]}–{bt['origins'][-1][:4]}, {bt['forecasts']:,} forecasts, "
                f"{bt['companies']} carriers)", "",
                (f"- Year-1 loss ratio, mean absolute error: model {y1['mae_model']:.2f} pts, with realized drivers "
                f"{y1.get('mae_model_known', float('nan')):.2f}, last four quarters {y1['mae_last4']:.2f}, company average {y1['mae_average']:.2f}."),
                (f"- Year-2: model {y2['mae_model']:.2f}, with realized drivers {y2.get('mae_model_known', float('nan')):.2f}, "
                f"last four quarters {y2['mae_last4']:.2f}, company average {y2['mae_average']:.2f}."),
                "- 80% interval coverage by horizon: " + ", ".join(f"h{h['h']} {h['cover80'] * 100:.0f}%" for h in bt["by_horizon"]),
                "- The gains are modest and fade: in year 2 a carrier's own long-run average forecasts as well or better.", ""]

    # stress results at severity 1, with the share that comes from the assumption overlays
    ref = refs["referenceSummaries"]
    off = refs.get("referenceSummariesNoOverlays", {})
    base = ref["baseline"]
    names = {s["key"]: s["name"] for s in model["scenarios"]}
    year1 = lambda s: sum(s["cr"][2][:4]) / 4
    out += ["## Stress scenarios at severity 1", "",
            ("Median year-1 combined-ratio change vs the baseline, and capital generated over eight quarters vs the "
            "baseline. Where a scenario carries an assumption overlay, the part of the change that the overlay "
            "contributes is shown separately."), ""]
    for key, by in ref.items():
        if key == "baseline":
            continue
        rows = []
        for cik, s in by.items():
            b = base[cik]
            d_cr = year1(s) - year1(b)
            d_cap = s["cap_8q"][2] - b["cap_8q"][2]
            d_off = year1(off[key][cik]) - year1(b) if key in off else None
            rows.append((by_cik[int(cik)]["ticker"], d_cr, d_cap, d_off))
        worst = sorted(rows, key=lambda r: -r[1])[:4]
        capw = sorted(rows, key=lambda r: r[2])[:3]
        hits = ", ".join(f"{t} {pts(d)}" + (f" (overlay {pts(d - o)})" if o is not None else "") for t, d, _, o in worst)
        out.append(f"- **{names.get(key, key)}**: biggest combined-ratio hits {hits}; biggest capital hits "
                   + ", ".join(f"{t} {pts(c, 0)} of equity" for t, _, c, _ in capw) + ".")
    out.append("")
    d = meta["diagnostics"]
    out += ["## Model diagnostics", "",
            (f"- {d['parameters_checked']} parameters checked: max R-hat {d['max_r_hat']:.3f}, minimum bulk ESS {d['min_ess_bulk']:.0f}, "
            f"{d['divergences']} divergences; sampling took {d['seconds']:.0f} s."), ""]
    (ROOT / "docs" / "findings.md").write_text("\n".join(out))
    # the README carries the same text between markers (headings demoted one level)
    readme = ROOT / "README.md"
    text = readme.read_text()
    a, b = "<!-- findings:start -->", "<!-- findings:end -->"
    if a in text and b in text:
        body = "\n".join(("#" + line) if line.startswith("## ") else line for line in out[4:]).strip()
        text = text[: text.index(a) + len(a)] + "\n" + body + "\n" + text[text.index(b):]
        readme.write_text(text)
    print("\n".join(out))


if __name__ == "__main__":
    main()
