"""Write the parity fixture for the dashboard's simulation engine (dashboard/src/engine.ts).

Runs the Python reference (sil/model/simulate.py) on the ROUNDED values exported to
dashboard/public/data/model.json, for three companies (Kinsale, RenaissanceRe, W. R. Berkley) under the
"polycrisis" scenario at severity 1.3 with overlays on, and under the baseline. The fixture embeds the exact
inputs it used, so the TypeScript test (dashboard/tests/engine.test.ts) stays meaningful after model.json is
re-exported: regenerate this fixture only when the engine's arithmetic changes.

Run from the project root:
  .venv/bin/python -I scripts/make_engine_fixture.py
"""

from __future__ import annotations

import json
import sys
from pathlib import Path

import numpy as np

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

from sil.model import simulate

DATA = ROOT / "dashboard" / "public" / "data"
OUT = ROOT / "dashboard" / "tests" / "fixtures" / "engine.json"
TICKERS = ("KNSL", "RNR", "WRB")
SCENARIO = "polycrisis"
SEVERITY = 1.3
STORE_DRAWS = 64  # full arrays for the first 64 draws; summaries cover all draws


def params_from_json(c: dict) -> simulate.CompanyParams:
    return simulate.CompanyParams(
        mu=np.array(c["mu"], dtype=float), rho=np.array(c["rho"], dtype=float),
        beta=np.array(c["beta"], dtype=float), lam=np.array(c["lam"], dtype=float),
        sigma=np.array(c["sigma"], dtype=float), expense_ratio=c["expenseRatio"], last_lrs=list(c["lastLrs"]),
        last_f=list(c["lastF"]),
        npe_q=c["npeQ"], growth=c["growth"], equity=c["equity"], inv_to_equity=c["invToEquity"],
        nii_yield=c["niiYield"], kappa=c["kappa"], kappa_c=c["kappaC"], d_rate=c["dRate"], d_fin=c["dFin"],
        eq_sec_to_equity=c["eqSecToEquity"], other_income_q=c["otherIncomeQ"], payout=c["payout"],
        exposures=dict(c["exposures"]),
    )


def base_from_json(b: dict) -> dict:
    return {
        "features": np.array(b["features"], dtype=float),
        "f": np.array(b["f"], dtype=float),
        "ust5y": np.array(b["ust5y"], dtype=float),
        "nfci": np.array(b["nfci"], dtype=float),
        "equity": np.array(b["equity"], dtype=float),
        "start": dict(b["start"]),
    }


def zero_shock(K: int, H: int) -> dict:
    z = [0.0] * H
    return {"features": [z] * K, "f": z, "ust5y": z, "nfci": z, "equity": z, "growth": z, "overlays": []}


def scenario_shock(s: dict) -> dict:
    return {**s["shock"], "overlays": s["overlays"]}


def raw_quantiles(sim: dict) -> dict:
    qs = [0.05, 0.25, 0.5, 0.75, 0.95]
    out = {k: np.quantile(sim[k], qs, axis=0).tolist() for k in ("lr", "cr", "roe", "bvx", "cap")}
    out["p_cr_over_100_count"] = (sim["cr"] > 1.0).sum(axis=0).tolist()
    return out


def main() -> None:
    model = json.loads((DATA / "model.json").read_text())
    companies = {c["cik"]: c for c in json.loads((DATA / "companies.json").read_text())}
    by_ticker = {companies[c["cik"]]["ticker"]: c for c in model["companies"]}
    if simulate.SEED_BASE != model["seedBase"] or simulate.H != len(model["horizon"]):
        raise SystemExit("model.json was written by a different engine version")
    if any("lastF" not in c for c in model["companies"]):
        raise SystemExit("model.json has no lastF (written before the attritional-level engine): re-export it first")
    scen = next(s for s in model["scenarios"] if s["key"] == SCENARIO)
    base = base_from_json(model["base"])
    K = len(model["features"])
    runs = []
    for ticker in TICKERS:
        c = by_ticker[ticker]
        p = params_from_json(c)
        for key, shock, sev in ((SCENARIO, scenario_shock(scen), SEVERITY), ("baseline", zero_shock(K, simulate.H), 0.0)):
            sim = simulate.simulate_company(c["stream"], p, base, shock, sev, overlays_on=True)
            runs.append({
                "ticker": ticker, "cik": c["cik"], "scenario": key, "severity": sev, "overlays": True,
                "out": {k: sim[k][:STORE_DRAWS].tolist() for k in ("lr", "cr", "roe", "bvx", "cap", "npe")},
                "summary": simulate.summarize(sim),
                "raw": raw_quantiles(sim),
            })
    fixture = {
        "note": "Generated by scripts/make_engine_fixture.py from the Python reference sil/model/simulate.py.",
        "seedBase": model["seedBase"],
        "draws": model["draws"],
        "storedDraws": STORE_DRAWS,
        "features": model["features"],
        "base": model["base"],
        "scenario": {"key": scen["key"], "shock": scen["shock"], "overlays": scen["overlays"]},
        "companies": [by_ticker[t] for t in TICKERS],
        "runs": runs,
    }
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(json.dumps(fixture, separators=(",", ":")))
    print(f"wrote {OUT.relative_to(ROOT)} ({OUT.stat().st_size / 1024:.0f} kB): "
          f"{len(runs)} runs, {model['draws']} draws x {simulate.H} quarters")


if __name__ == "__main__":
    main()
